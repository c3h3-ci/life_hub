    global _current_hass
    _current_hass = hass

    for svc in _SERVICES:
        if not hass.services.has_service(DOMAIN, svc.name):
            hass.services.async_register(
                DOMAIN, svc.name, svc.handler, schema=svc.schema,
                supports_response=SupportsResponse.OPTIONAL,
            )
        else:
            _LOGGER.debug("Service %s already registered, skipping", svc.name)
