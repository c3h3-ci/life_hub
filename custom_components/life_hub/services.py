"""Life Hub services — all providers.

Strategy:
- Generic dispatch handlers (``{tool} + {params} → client.{tool}(**params)``)
  are generated by ``_make_dispatch_handler()`` to eliminate REST provider boilerplate.
- MCP providers use ``_make_mcp_handler()`` which maps unified
  ``{tool, params}`` to ``client.call_tool(tool, params)``.
- Providers with special dispatch logic (yiming, meituan) keep hand-written closures.
- Registration is a single declarative list at the bottom, not 350 lines.
"""

